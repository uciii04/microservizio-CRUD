package com.example.GestioneCatalogo.model;

public class Barcode {
	
	private String codice;
    private String tipo;
	
    
    public String getCodice() {
		return codice;
	}
	public void setCodice(String codice) {
		this.codice = codice;
	}
	
	public String getTipo() {
		return tipo;
	}
	public void setTipo(String tipo) {
		this.tipo = tipo;
	}

}
